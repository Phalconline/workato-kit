#!/usr/bin/env python3.14
"""Refresh the lookup-table descriptions of the workspace folder. Read-only towards Workato.

    scripts/sync_lookup_tables.py            write the files
    scripts/sync_lookup_tables.py --check    write nothing; exit 1 if a file is out of date

One Markdown file per lookup table of the Dev workspace, plus README.md as the index, in
workato/workspaces/<workspace>/lookup-tables/. The script reads the list of tables and their
column definitions only, every page of it. It never reads rows: table data does not belong in
the repository.

Generated: the frontmatter (id, name, scope), the list of fields and the "Used by" list: the
documented recipes whose entry in the recipe index names the table. scripts/build_index.py
records a table for a recipe when the registry lists the table's id under `tables` of a project.
Written by a person and kept by the script: the Purpose text, the description of each field, and
the `verified` and `personal_data` values of the frontmatter; they stay with the table when it is
renamed in Workato. Columns still called "Untitled column N" are unused and are left out.

Exit status: 0 done, or with --check everything is up to date; 1 with --check otherwise;
2 when Workato could not be read.
"""

import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from lib import cli, wkrepo
from lib.wkrepo import Json

ROOT = wkrepo.ROOT
EMPTY = "Not documented yet."
DATA_TABLE_ENTRY = "data table "  # how scripts/build_index.py lists a data table by its id
UNTITLED = re.compile(r"Untitled column \d+")
PERSONAL_FIELD = re.compile(r"e-?mail|user", re.IGNORECASE)
PURPOSE = re.compile(r"^## Purpose\n\n(.*?)\n\n## Fields", re.DOTALL | re.MULTILINE)
FIELD_ROW = re.compile(r"^\| `([^`]+)` \| (.*?) \|$", re.MULTILINE)
README_HEAD = """\
# Lookup tables

One file per lookup table of the workspace: what the table is for and what its fields mean.
**The data of a table never enters this repository.** A table can hold personal data: the
"Personal data" column is a guess from the field names until a person sets `personal_data` in
the file of the table.

Generated by `scripts/sync_lookup_tables.py`: this index, each file's field list and its
"Used by" list. Written by hand and kept by the script: the Purpose text and the
description of each field. To document a table, fill those in and set `verified` in the
frontmatter to how you know (`from-recipe-docs`, `read-in-ui`), then run the script.

Scope is the Workato project a table belongs to, or `global`. "Used by" lists only what the
recipe index records: an empty list does not prove that no recipe reads the table.

| Table | Scope | Fields | Documented recipes using it | Personal data | Purpose written |
|---|---|---|---|---|---|
"""


def escape_pipe(text: str) -> str:
    """Escape the pipe of a name so that it does not split a Markdown table row."""
    return text.replace("|", "\\|")


def columns(table: Json) -> list[str]:
    """Return the names of the columns of a table that are in use."""
    schema = table.get("schema")
    cols = json.loads(schema) if isinstance(schema, str) else (schema or [])
    labels = [" ".join((col.get("label") or col.get("name") or "").split()) for col in cols]
    return [label for label in labels if label and not UNTITLED.fullmatch(label)]


def used_by(table: Json, index: list[Json]) -> list[tuple[str, str]]:
    """Return (recipe name, doc path) of every documented recipe that names the table."""
    by_id = re.compile(rf"(?<!\d){table['id']}(?!\d)")
    found = {}
    for entry in index:
        for item in entry.get("tables") or []:
            text = item if isinstance(item, str) else json.dumps(item)
            if text.startswith(DATA_TABLE_ENTRY):
                continue  # a data table has ids of its own: the same number is another table
            named = by_id.search(text) or table["name"].lower() in text.lower()
            if named and entry.get("doc"):
                found[entry["recipe_id"]] = (str(entry["name"]).strip('"'), entry["doc"])
    return sorted(found.values())


def existing(path: Path) -> Json:
    """Return the hand-written parts of a file: purpose, field texts, verified, personal_data."""
    kept: Json = {"purpose": EMPTY, "fields": {}, "verified": "unverified", "personal_data": None}
    if not path.exists():
        return kept
    text = path.read_text(encoding="utf-8")
    for key in ("verified", "personal_data"):
        match = re.search(rf"^{key}:\s*(.+)$", text, re.MULTILINE)
        if match:
            kept[key] = match.group(1).strip()
    purpose = PURPOSE.search(text)
    if purpose:
        kept["purpose"] = purpose.group(1).strip()
    kept["fields"] = {name: description.strip() for name, description in FIELD_ROW.findall(text)}
    return kept


def personal_data(fields: list[str], kept: Json) -> str:
    """Return the person's answer, or a guess from the field names."""
    if kept["personal_data"]:
        return str(kept["personal_data"])
    return "yes" if any(PERSONAL_FIELD.search(field) for field in fields) else "no"


def render(
    table: Json, scope: str, fields: list[str], users: list[tuple[str, str]], kept: Json
) -> str:
    """Return the Markdown file of one table."""
    lines = [
        "---",
        f"table_id: {table['id']}",
        f"name: {json.dumps(table['name'], ensure_ascii=False)}",
        f"scope: {scope}",
        f"personal_data: {personal_data(fields, kept)}",
        f"verified: {kept['verified']}",
        "---",
        "",
        f"# {table['name']} (`{table['id']}`)",
        "",
        "## Purpose",
        "",
        kept["purpose"],
        "",
        "## Fields",
        "",
        "| Field | Description |",
        "|---|---|",
        *[f"| `{field}` | {kept['fields'].get(field, '')} |" for field in fields],
        "",
        "## Used by",
        "",
    ]
    if users:
        folder = wkrepo.lookup_tables()
        for name, doc in users:
            link = (ROOT / doc).relative_to(folder, walk_up=True).as_posix()
            lines.append(f"- [{escape_pipe(name)}]({link})")
    else:
        lines.append("The recipe index names no documented recipe for this table.")
    return "\n".join(lines) + "\n"


def remote_tables() -> list[Json]:
    """Return every lookup table of Dev with its column definitions, reading all pages."""
    api = wkrepo.api("dev")
    found: dict[int, Json] = {}
    page = 1
    while True:
        batch = api.get("/lookup_tables", {"page": page, "per_page": wkrepo.PAGE_SIZE})
        if not isinstance(batch, list) or not all(isinstance(table, dict) for table in batch):
            raise cli.Error("Workato answered GET /lookup_tables with something that is no list")
        new = {table["id"]: table for table in batch if table["id"] not in found}
        found.update(new)
        # A short page is the last one; a page without a new table means paging is not honored.
        if len(batch) < wkrepo.PAGE_SIZE or not new:
            return list(found.values())
        page += 1


def wanted_files() -> dict[Path, str]:
    """Read the tables from Workato and return every file the folder should hold."""
    folder = wkrepo.lookup_tables()
    tables = remote_tables()
    index_file = wkrepo.inventory() / "recipes-index.json"
    index = json.loads(index_file.read_text(encoding="utf-8")) if index_file.exists() else []
    projects = {
        entry["dev"]["project_id"]: entry["name"]
        for entry in wkrepo.registry()["projects"].values()
        if "dev" in entry
    }
    files: dict[Path, str] = {}
    rows = []
    for table in sorted(tables, key=lambda table: table["name"].lower()):
        scope = projects.get(table.get("project_id"), "global")
        path = folder / f"{table['id']}-{wkrepo.slug(table['name']) or 'unnamed'}.md"
        # After a rename in Workato the file has another name: its hand-written parts move over.
        earlier = [old for old in sorted(folder.glob(f"{table['id']}-*.md")) if old != path]
        kept = existing(path if path.exists() or not earlier else earlier[0])
        fields, users = columns(table), used_by(table, index)
        files[path] = render(table, scope, fields, users, kept)
        written = "yes" if kept["purpose"] != EMPTY else "no"
        rows.append(
            f"| [{escape_pipe(table['name'])}]({path.name}) | {scope} | {len(fields)} | "
            f"{len(users)} | {personal_data(fields, kept)} | {written} |"
        )
    files[folder / "README.md"] = README_HEAD + "\n".join(rows) + "\n"
    return files


def main(argv: list[str] | None = None) -> int:
    """Write or check the lookup-table files; return the exit status."""
    parser = cli.parser(__doc__)
    parser.add_argument("--check", action="store_true", help="compare only; write nothing")
    args = parser.parse_args(argv)

    files = wanted_files()
    stale = []
    for path, text in files.items():
        if path.exists() and path.read_text(encoding="utf-8") == text:
            continue
        stale.append(path.relative_to(ROOT).as_posix())
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    for path in sorted(wkrepo.lookup_tables().glob("[0-9]*.md")):
        if path not in files:
            renamed = any(new.name.startswith(path.name.split("-")[0] + "-") for new in files)
            reason = "its table was renamed" if renamed else "table no longer exists"
            stale.append(f"{path.relative_to(ROOT).as_posix()} ({reason})")
            if not args.check:
                path.unlink()
    if args.check:
        for relative in stale:
            print("out of date:", relative)
        return cli.EXIT_FINDINGS if stale else cli.EXIT_OK
    print(f"{len(files) - 1} lookup tables, {len(stale)} file(s) written.")
    return cli.EXIT_OK


if __name__ == "__main__":
    cli.run(main)
